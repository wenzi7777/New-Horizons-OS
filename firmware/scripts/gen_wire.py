#!/usr/bin/env python3
"""Generate the NHO/Arduino/1 wire constants from spec/wire.json.

    firmware/scripts/gen_wire.py [--check] [--desktop DIR] [--gateway DIR]

Writes (or with --check, compares):
  this repo  firmware/libraries/nhos_core/src/PacketWireConstants.h, TimeWireConstants.h
             (the library the firmware and the Hub both build with)
  Desktop    backend/newhorizons_backend/wire.py
  Gateway    newhorizons_gateway/wire.py

The sibling repositories default to the checkouts beside this one; a missing
one is skipped with a note unless it was named explicitly.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SPEC = REPO / "spec" / "wire.json"
NOTICE = "GENERATED by NewHorizonsOS-OTA firmware/scripts/gen_wire.py from spec/wire.json."
DO_NOT_EDIT = "Do not edit: change spec/wire.json and regenerate; CI fails when this copy drifts."


def load_spec() -> dict:
    def ints(value):
        if isinstance(value, dict):
            return {k: ints(v) for k, v in value.items() if not k.startswith("_")}
        if isinstance(value, str) and value.lower().startswith("0x"):
            return int(value, 16)
        return value
    return ints(json.loads(SPEC.read_text(encoding="utf-8")))


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def packet_header(spec: dict) -> str:
    p = spec["packet"]
    ports = spec["ports"]
    lines = [
        f"// {NOTICE}",
        f"// {DO_NOT_EDIT}",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace nhos {",
        "",
        f"constexpr uint16_t kUdpStreamPort = {ports['stream']};",
        f"constexpr uint16_t kControlPort = {ports['control']};",
        f"constexpr uint16_t kDiscoveryPort = {ports['discovery']};",
        "",
        f"constexpr uint16_t kPacketMagic = 0x{p['magic']:04X};",
        f"constexpr uint8_t kPacketVersion = {p['version']};",
    ]
    for name, bit in p["flags"].items():
        lines.append(f"constexpr uint8_t kPacketFlag{camel(name)} = 0x{bit:02X};")
    lines += [
        f"constexpr size_t kPacketHeaderLen = {p['header_len']};",
        f"constexpr size_t kPacketHmacLen = {p['hmac_len']};",
        "",
        f"constexpr uint8_t kPacketBaseImuFloatCount = {p['imu_floats']};",
        f"constexpr uint8_t kPacketMagFloatCount = {p['mag_floats']};",
        "constexpr size_t kPacketBaseImuBytes = kPacketBaseImuFloatCount * sizeof(float);",
        "constexpr size_t kPacketMagBytes = kPacketMagFloatCount * sizeof(float);",
        f"constexpr size_t kPacketBatteryBytes = {p['battery_bytes']};",
        "",
        f"constexpr size_t kPacketExtensionTlvHeaderLen = {p['extension_tlv_header_len']};",
        "// All TLVs of one packet together; bounded so a data frame never grows",
        "// beyond the ESP-NOW budget.",
        f"constexpr size_t kPacketExtensionBudget = {p['extension_budget']};",
        f"constexpr size_t kEspNowDataFrameBudget = {p['espnow_data_frame_budget']};",
        "",
        "// Extension TLV types (spec/PROTOCOL.md 3.1).",
    ]
    for name, value in p["extension_types"].items():
        lines.append(f"constexpr uint8_t kPacketExt{camel(name)} = 0x{value:02X};")
    e = p["app_event"]
    lines += [
        f"constexpr uint8_t kAppEventFlagValue = 0x{e['flag_value']:02X};",
        f"constexpr size_t kAppEventMaxApp = {e['max_app']};",
        f"constexpr size_t kAppEventMaxEvent = {e['max_event']};",
        f"constexpr size_t kAppEventMaxDetail = {e['max_detail']};",
        "",
        "}  // namespace nhos",
        "",
    ]
    return "\n".join(lines)


def time_header(spec: dict) -> str:
    t = spec["time"]
    lines = [
        f"// {NOTICE}",
        f"// {DO_NOT_EDIT}",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace nhos {",
        "",
        "// Must not collide with HELLO 0xE1 / POLL 0xE2 / PAIRED 0xE3 / fragment",
        "// 0xE5 / OTA chunk ack 0xE6 / control ack 0xE7.",
        f"static constexpr uint8_t kEspNowTimeReqMagic = 0x{t['req_magic']:02X};",
        f"static constexpr uint8_t kEspNowTimeRespMagic = 0x{t['resp_magic']:02X};",
        f"static constexpr uint8_t kEspNowTimeWireVersion = {t['version']};",
        "",
        "// magic(1) version(1) seq(1) flags(1) t1(8)",
        f"static constexpr size_t kEspNowTimeReqLen = {t['req_len']};",
        "// magic(1) version(1) seq(1) flags(1) t1(8) t2(8) t3(8) uncertaintyMs(2) reserved(2)",
        f"static constexpr size_t kEspNowTimeRespLen = {t['resp_len']};",
        "",
        "// TIME_RESP flags: bit0 = the server's (Hub's, Gateway's) clock is synced;",
        "// the high nibble is its TimeSource.",
        f"static constexpr uint8_t kEspNowTimeFlagHubSynced = 0x{t['flags']['synced']:02X};",
        "",
        "}  // namespace nhos",
        "",
    ]
    return "\n".join(lines)


def python_module(spec: dict) -> str:
    p = spec["packet"]
    t = spec["time"]
    ports = spec["ports"]
    lines = [
        f'"""{NOTICE}',
        "",
        DO_NOT_EDIT,
        '"""',
        "",
        f'PROTOCOL = "{spec["protocol"]}"',
        f"STREAM_PORT = {ports['stream']}",
        f"CONTROL_PORT = {ports['control']}",
        f"DISCOVERY_PORT = {ports['discovery']}",
        "",
        "# The current (v5) packet. Older versions are frozen history, kept by the parsers.",
        f"PACKET_MAGIC = 0x{p['magic']:04X}",
        f"PACKET_VERSION_V5 = {p['version']}",
        f"HEADER_LEN_V5 = {p['header_len']}",
        f"HMAC_LEN = {p['hmac_len']}",
        f"IMU_BYTES = {p['imu_floats']} * 4",
        f"MAG_BYTES = {p['mag_floats']} * 4",
        f"BATTERY_BYTES_V5 = {p['battery_bytes']}",
        f"EXTENSION_TLV_HEADER_LEN = {p['extension_tlv_header_len']}",
        f"EXTENSION_BUDGET = {p['extension_budget']}",
        f"ESPNOW_DATA_FRAME_BUDGET = {p['espnow_data_frame_budget']}",
    ]
    for name, bit in p["flags"].items():
        lines.append(f"FLAG_{name.upper()} = 0x{bit:02X}")
    lines += ["", "# Extension TLV types (spec/PROTOCOL.md 3.1)."]
    for name, value in p["extension_types"].items():
        lines.append(f"EXT_{name.upper()} = 0x{value:02X}")
    e = p["app_event"]
    lines += [
        f"APP_EVENT_FLAG_VALUE = 0x{e['flag_value']:02X}",
        f"APP_EVENT_MAX_APP = {e['max_app']}",
        f"APP_EVENT_MAX_EVENT = {e['max_event']}",
        f"APP_EVENT_MAX_DETAIL = {e['max_detail']}",
    ]
    lines += [
        "",
        "# Time exchange (TIME_REQ / TIME_RESP), over ESP-NOW and over UDP.",
        f"TIME_REQ_MAGIC = 0x{t['req_magic']:02X}",
        f"TIME_RESP_MAGIC = 0x{t['resp_magic']:02X}",
        f"TIME_WIRE_VERSION = {t['version']}",
        f"TIME_REQ_LEN = {t['req_len']}",
        f"TIME_RESP_LEN = {t['resp_len']}",
        f"TIME_FLAG_SYNCED = 0x{t['flags']['synced']:02X}",
        "",
    ]
    return "\n".join(lines)


def outputs(spec: dict) -> list[tuple[str, str | None, str, list[tuple[str, str]]]]:
    """(label, explicit dir or None, default sibling name, [(relative path, text)])."""
    packet = packet_header(spec)
    time = time_header(spec)
    py = python_module(spec)
    return [
        ("firmware", str(REPO), "NewHorizonsOS-OTA", [
            ("firmware/libraries/nhos_core/src/PacketWireConstants.h", packet),
            ("firmware/libraries/nhos_core/src/TimeWireConstants.h", time),
        ]),
        ("desktop", None, "New-Horizons-Desktop", [("backend/newhorizons_backend/wire.py", py)]),
        ("gateway", None, "New-Horizons-Gateway", [("newhorizons_gateway/wire.py", py)]),
    ]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs")
    for name in ("desktop", "gateway"):
        parser.add_argument(f"--{name}", help=f"the {name} checkout (default: the sibling directory)")
    args = parser.parse_args(argv)
    spec = load_spec()
    failures = 0
    for label, fixed, sibling, files in outputs(spec):
        explicit = fixed or getattr(args, label, None)
        root = Path(explicit) if explicit else REPO.parent / sibling
        if not root.is_dir():
            if explicit:
                print(f"{label}: no such directory {root}", file=sys.stderr)
                return 2
            print(f"  skip {label}: {root} is not checked out")
            continue
        for relative, text in files:
            path = root / relative
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if args.check:
                if current == text:
                    print(f"  ok {label}: {relative}")
                else:
                    print(f"  DRIFT {label}: {relative} differs from spec/wire.json; run gen_wire.py", file=sys.stderr)
                    failures += 1
            elif current != text:
                path.write_text(text, encoding="utf-8")
                print(f"  wrote {path}")
            else:
                print(f"  unchanged {path}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
