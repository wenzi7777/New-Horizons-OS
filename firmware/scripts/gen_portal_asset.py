#!/usr/bin/env python3
"""Generate the SoftAP setup page asset from nhos_core/portal/setup_portal.html.

    firmware/scripts/gen_portal_asset.py [--check]

Writes (or with --check, compares) nhos_core/src/SetupPortalAsset.h: the page
with indentation and blank lines stripped, gzipped, as a PROGMEM byte array.
SetupPortal serves it as-is with Content-Encoding: gzip, so the page costs
flash only, never heap.
"""
from __future__ import annotations

import argparse
import gzip
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CORE = REPO / "firmware" / "libraries" / "nhos_core"
SOURCE = CORE / "portal" / "setup_portal.html"
OUTPUT = CORE / "src" / "SetupPortalAsset.h"


def minify(html: str) -> str:
    # The page avoids multi-line strings and // comments, so dropping each
    # line's indentation and the blank lines is safe.
    return "\n".join(line.strip() for line in html.splitlines() if line.strip()) + "\n"


def header() -> str:
    raw = minify(SOURCE.read_text(encoding="utf-8")).encode("utf-8")
    packed = gzip.compress(raw, compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{b:02x}" for b in packed[i:i + 16]) for i in range(0, len(packed), 16)]
    body = ",\n  ".join(rows)
    return (
        "// GENERATED by firmware/scripts/gen_portal_asset.py from portal/setup_portal.html.\n"
        "// Do not edit: change the HTML and regenerate; tests fail when this copy drifts.\n"
        "#pragma once\n"
        "\n"
        "#include <pgmspace.h>\n"
        "#include <stdint.h>\n"
        "\n"
        "namespace nhos {\n"
        "\n"
        f"// {len(raw)} bytes of HTML, {len(packed)} gzipped.\n"
        f"const uint8_t kSetupPortalGz[] PROGMEM = {{\n  {body}\n}};\n"
        "\n"
        "}  // namespace nhos\n"
    )


def unpack(header_text: str) -> bytes | None:
    match = re.search(r"\{\n(.*?)\n\};", header_text, re.S)
    if not match:
        return None
    try:
        return gzip.decompress(bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", match.group(1))))
    except OSError:
        return None


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the generated header differs")
    args = parser.parse_args(argv)
    text = header()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if args.check:
        # Compare what the header unpacks to, not its bytes: zlib builds
        # differ (macOS vs the Linux CI), so the same page can gzip to
        # different bytes.
        if current is not None and unpack(current) == minify(SOURCE.read_text(encoding="utf-8")).encode("utf-8"):
            print(f"  ok {OUTPUT.relative_to(REPO)}")
            return 0
        print(f"  DRIFT {OUTPUT.relative_to(REPO)} differs from setup_portal.html; run gen_portal_asset.py",
              file=sys.stderr)
        return 1
    if current != text:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"  wrote {OUTPUT}")
    else:
        print(f"  unchanged {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
