#!/usr/bin/env python3
"""Generate spec/commands.md and spec/config.md from the firmware's own tables.

    firmware/scripts/gen_spec_docs.py [--check]

commands.md comes from ControlCommandTable.cpp (the dispatch table, so it
cannot list a command the firmware does not handle), config.md from
ConfigRegistry.cpp's kEntries. --check fails when a committed copy differs.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FIRMWARE = REPO / "firmware" / "newhorizons_os"
SPEC = REPO / "spec"
HEADER = "<!-- GENERATED by firmware/scripts/gen_spec_docs.py from {source}. Do not edit; regenerate. -->"

ROW = re.compile(
    r'\{"(?P<name>[a-z_0-9]+)", &ControlServer::(?P<handler>cmd\w+), (?P<flags>[^,]+),\s*'
    r'"(?P<summary>(?:[^"\\]|\\.)*)"\}'
)
FLAG_COLUMNS = [
    ("kCmdNeedsMaintenance", "maintenance"),
    ("kCmdHeavy", "heavy"),
    ("kCmdQuietLed", "quiet"),
    ("kCmdInternal", "internal"),
    ("kCmdStatusSnapshot", "status snapshot"),
]


def commands_md() -> str:
    table = (FIRMWARE / "ControlCommandTable.cpp").read_text(encoding="utf-8")
    rows = [m.groupdict() for m in ROW.finditer(table)]
    handlers: dict[str, list[str]] = {}
    for row in rows:
        handlers.setdefault(row["handler"], []).append(row["name"])
    out = [
        HEADER.format(source="firmware/newhorizons_os/ControlCommandTable.cpp"),
        "",
        "# Device commands",
        "",
        f"{len(rows)} commands, in dispatch-table order. A device reports the same table at run time",
        "with the `commands` command (firmware v1.15.0+). See PROTOCOL.md for the request and",
        "reply envelope.",
        "",
        "Flags:",
        "",
        "- **maintenance**: refused with `maintenance_required` outside maintenance mode.",
        "- **heavy**: over UDP, acked at once and run in the next gap between scans.",
        "- **quiet**: never flashes the command LED (any command can ask for that with `\"quiet\":true`).",
        "- **internal**: sent by the Desktop/Hub itself; not offered to users.",
        "- **status snapshot**: the reply is a status the Desktop merges into its device state.",
        "",
        "| Command | Flags | Summary |",
        "|---|---|---|",
    ]
    for row in rows:
        flags = {f.strip() for f in row["flags"].split("|")}
        names = [label for flag, label in FLAG_COLUMNS if flag in flags]
        summary = row["summary"].replace('\\"', '"').replace("|", "\\|")
        aliases = [n for n in handlers[row["handler"]] if n != row["name"]]
        if aliases:
            summary += f" (same handler as `{'`, `'.join(aliases)}`)"
        out.append(f"| `{row['name']}` | {', '.join(names)} | {summary} |")
    out.append("")
    return "\n".join(out)


def _constants() -> dict[str, str]:
    """Numeric and string constants from the firmware headers, by name."""
    values: dict[str, str] = {}
    for path in sorted(FIRMWARE.glob("*.h")):
        text = path.read_text(encoding="utf-8")
        for m in re.finditer(r"constexpr\s+[\w:]+\s+(k\w+)\s*=\s*([-0-9.]+f?)\s*;", text):
            values.setdefault(m.group(1), m.group(2).rstrip("f"))
        for m in re.finditer(r'constexpr\s+char\s+(k\w+)\[\]\s*=\s*"([^"]*)"\s*;', text):
            values.setdefault(m.group(1), m.group(2))
    return values


def _fields(entry: str) -> list[str]:
    """Top-level comma-separated fields of one `{...}` initializer."""
    fields, current, in_string = [], "", False
    i = 0
    while i < len(entry):
        c = entry[i]
        if c == '"' and (i == 0 or entry[i - 1] != "\\"):
            in_string = not in_string
        if c == "," and not in_string:
            fields.append(current.strip())
            current = ""
        else:
            current += c
        i += 1
    fields.append(current.strip())
    return fields


def _string(field: str) -> str:
    """A C string literal, adjacent literals joined; nullptr -> ''."""
    if field == "nullptr":
        return ""
    return "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', field))


def config_md() -> str:
    source = (FIRMWARE / "ConfigRegistry.cpp").read_text(encoding="utf-8")
    body = source[source.index("const ConfigEntry kEntries[] = {"):]
    body = body[body.index("{") + 1:body.index("\n};")]
    constants = _constants()

    def value(field: str) -> str:
        if field.startswith('"') or field == "nullptr":
            return _string(field)
        return constants.get(field, field)

    entries = re.findall(r"\{((?:[^{}\"]|\"(?:[^\"\\]|\\.)*\")*)\}", body)
    out = [
        HEADER.format(source="firmware/newhorizons_os/ConfigRegistry.cpp"),
        "",
        "# Device configuration",
        "",
        f"{len(entries)} keys, read with `config_get --path <key>` and written with",
        "`config_set --path <key> --value <v>` (or the listed command directly). `config_schema`",
        "returns this table, with a hash, at run time.",
        "",
        "| Key | Type | Range / values | Applied by | Summary |",
        "|---|---|---|---|---|",
    ]
    for entry in entries:
        path, kind, command, argument, lo, hi, allowed, summary = _fields(entry)
        kind = kind.split("::")[-1].lower()
        if kind in ("int", "float"):
            span = f"{value(lo)} – {value(hi)}"
        elif kind == "enum":
            span = ", ".join(f"`{v}`" for v in value(allowed).split(","))
        else:
            span = ""
        out.append(
            f"| `{_string(path)}` | {kind} | {span} | `{_string(command)} {_string(argument)}` | {_string(summary)} |"
        )
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    failures = 0
    for name, text in (("commands.md", commands_md()), ("config.md", config_md())):
        path = SPEC / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current == text:
                print(f"  ok spec/{name}")
            else:
                print(f"  DRIFT spec/{name}; run firmware/scripts/gen_spec_docs.py", file=sys.stderr)
                failures += 1
        elif current != text:
            path.write_text(text, encoding="utf-8")
            print(f"  wrote spec/{name}")
        else:
            print(f"  unchanged spec/{name}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
